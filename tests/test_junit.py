def test_junit_test_fails_against_half_even_variant():
    """
    End-to-end test: generate HALF_EVEN variant, compile it, generate JUnit test,
    run test against HALF_EVEN variant (should FAIL), then against correct Java (should PASS).
    """
    from coroner.parse.schema import load_schema
    
    schema_path = Path("samples/credit-fees/schema.json")
    correct_java_path = Path("samples/credit-fees/java/CreditFees.java")
    
    if not schema_path.exists() or not correct_java_path.exists():
        pytest.skip("Credit-fees files not available")
    
    junit_jar = Path("build/junit/junit-platform-console-standalone-6.1.3.jar")
    if not junit_jar.exists():
        pytest.skip("JUnit jar not available (run 'make junit-jars')")
    
    if shutil.which("javac") is None:
        pytest.skip("javac not available")
    
    if shutil.which("java") is None:
        pytest.skip("java not available")
    
    # Load schema
    schema = load_schema(str(schema_path))
    
    # Create minimal case (from review R-49: PRINCIPAL -0.21, FEE-RATE 0.25510, segment P)
    minimal_case = CaseResult(
        case_id="GEN-001213",
        divergent=True,
        divergent_fields=[("FEE-AMOUNT", "-0000000.05", "-0000000.04")]
    )
    
    input_row = {
        "CASE-ID": "GEN-001213",
        "PRINCIPAL": "-0.21",
        "FEE-RATE": "0.25510",
        "CUSTOMER-SEGMENT": "P",
        "DURATION-MONTHS": "12",
        "INCOME": "30000.00"
    }
    
    expected_output = {
        "CASE-ID": "GEN-001213",
        "FEE-AMOUNT": "-0000000.05",
        "REASON-CODE": "R01"
    }
    
    # Create build directories
    build_test_dir = Path("build/test_junit_e2e")
    build_test_dir.mkdir(parents=True, exist_ok=True)
    
    build_java_dir = Path("build/test_junit_e2e/java")
    build_java_dir.mkdir(exist_ok=True)
    
    # Generate HALF_EVEN variant
    half_even_path = build_test_dir / "CreditFees.java"
    correct_content = correct_java_path.read_text()
    half_even_content = correct_content.replace("RoundingMode.HALF_UP", "RoundingMode.HALF_EVEN")
    half_even_path.write_text(half_even_content)
    
    # Compile HALF_EVEN variant
    compile_result = subprocess.run(
        ["javac", "-d", str(build_java_dir), str(half_even_path)],
        capture_output=True,
        timeout=30
    )
    assert compile_result.returncode == 0, f"HALF_EVEN compilation failed: {compile_result.stderr.decode()}"
    
    # Generate JUnit test
    junit_test_path = build_test_dir / "ZombieRegressionTest.java"
    generate_junit_test(
        minimal_case=minimal_case,
        input_row=input_row,
        expected_output=expected_output,
        java_class="CreditFees",
        schema=schema,
        output_path=str(junit_test_path)
    )
    
    # Compile JUnit test
    build_junit_dir = build_test_dir / "junit_classes"
    build_junit_dir.mkdir(exist_ok=True)
    compile_junit_result = subprocess.run(
        ["javac", "-cp", str(junit_jar), "-d", str(build_junit_dir), str(junit_test_path)],
        capture_output=True,
        timeout=30
    )
    assert compile_junit_result.returncode == 0, f"JUnit test compilation failed: {compile_junit_result.stderr.decode()}"
    
    # Run JUnit test against HALF_EVEN variant (should FAIL)
    run_junit_result = subprocess.run(
        [
            "java",
            f"-Dcoroner.java.classpath={build_java_dir.resolve()}",
            "-jar", str(junit_jar),
            "execute",
            "--class-path", str(build_junit_dir),
            "--select-class", "ZombieRegressionTest"
        ],
        capture_output=True,
        timeout=30
    )
    
    # Test should FAIL against HALF_EVEN variant
    assert run_junit_result.returncode != 0, "JUnit test should FAIL against HALF_EVEN variant"
    output = run_junit_result.stdout.decode()
    assert "FAILED" in output or "failures" in output.lower(), f"Expected test failure, got: {output}"
    
    # Now compile correct Java and run test again (should PASS)
    compile_correct_result = subprocess.run(
        ["javac", "-d", str(build_java_dir), str(correct_java_path)],
        capture_output=True,
        timeout=30
    )
    assert compile_correct_result.returncode == 0, f"Correct Java compilation failed: {compile_correct_result.stderr.decode()}"
    
    # Run JUnit test against correct Java (should PASS)
    run_correct_result = subprocess.run(
        [
            "java",
            f"-Dcoroner.java.classpath={build_java_dir.resolve()}",
            "-jar", str(junit_jar),
            "execute",
            "--class-path", str(build_junit_dir),
            "--select-class", "ZombieRegressionTest"
        ],
        capture_output=True,
        timeout=30
    )
    
    # Test should PASS against correct Java
    assert run_correct_result.returncode == 0, f"JUnit test should PASS against correct Java. Output: {run_correct_result.stdout.decode()}\nStderr: {run_correct_result.stderr.decode()}"
    output_correct = run_correct_result.stdout.decode()
    assert "successful" in output_correct.lower() or "passed" in output_correct.lower(), f"Expected test success, got: {output_correct}"

