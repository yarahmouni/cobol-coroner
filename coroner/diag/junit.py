"""JUnit test generation module for Coroner."""

import subprocess
from pathlib import Path
from coroner.compare import CaseResult
from coroner.parse.schema import Schema


def generate_junit_test(
    minimal_case: CaseResult,
    input_row: dict[str, str],
    expected_output: dict[str, str],
    java_class: str,
    schema: Schema,
    output_path: str,
    card: str | None = None,
    minimal_input_csv_path: str | None = None,
    minimal_cobol_output_csv_path: str | None = None
) -> None:
    """
    Generate a JUnit 5 source test that reproduces the divergence.
    
    For single-case schemas: writes the minimal case input to a temp file, runs the Java program
    as a subprocess, and asserts the divergent field equals the COBOL value.
    
    For multi-row schemas (case_rows): writes the minimal case input rows (from minimal_case_input.csv)
    to a temp file, runs the Java program, and asserts the whole output file equals the COBOL output
    (from minimal_case_cobol_output.csv).
    
    Args:
        minimal_case: The minimal failing case
        input_row: Input values for the minimal case (single case only)
        expected_output: Expected COBOL output values (single case only)
        java_class: Java main class name (e.g., "CreditFees")
        schema: Schema with column definitions
        output_path: Where to write ZombieRegressionTest.java
        card: Optional Given/When/Then card to prepend as header comment
        minimal_input_csv_path: Path to minimal_case_input.csv (multi-row only)
        minimal_cobol_output_csv_path: Path to minimal_case_cobol_output.csv (multi-row only)
    """
    # Extract divergent field info
    if not minimal_case.divergent_fields:
        raise ValueError("Minimal case has no divergent fields")
    
    first_divergent = minimal_case.divergent_fields[0]
    
    # Handle structured divergent_fields
    if isinstance(first_divergent, dict):
        divergent_field = first_divergent.get("field_name", "<row>")
        cobol_value = first_divergent.get("cobol_value", str(first_divergent.get("cobol_values", {})))
        java_value = first_divergent.get("java_value", str(first_divergent.get("java_values", {})))
    else:
        # Legacy tuple format (shouldn't happen with new code)
        divergent_field, cobol_value, java_value = first_divergent
    
    # Build card header if provided
    card_header = ""
    if card:
        # Format card as a block comment
        card_lines = card.split('\n')
        card_header = "/**\n * Given/When/Then card:\n *\n"
        for line in card_lines:
            card_header += f" * {line}\n"
        card_header += " */\n\n"
    
    # Check if this is a multi-row case
    is_multirow = schema.case_rows is not None
    
    if is_multirow:
        # Multi-row case: read input and output CSV files
        if not minimal_input_csv_path or not minimal_cobol_output_csv_path:
            raise ValueError("Multi-row case requires minimal_input_csv_path and minimal_cobol_output_csv_path")
        
        input_csv_content = Path(minimal_input_csv_path).read_text()
        expected_output_content = Path(minimal_cobol_output_csv_path).read_text()
        
        # Escape for Java string
        input_csv_escaped = input_csv_content.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", "\\n")
        expected_output_escaped = expected_output_content.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", "\\n")
        
        # Build header comment
        header = f"""/**
 * Generated by Coroner from minimal failing case.
 * 
 * Case ID: {minimal_case.case_id}
 * Divergent field: {divergent_field}
 * COBOL value: {cobol_value}
 * Java value: {java_value}
 * 
 * This test reproduces the divergence on the Java side.
 * Multi-row case: compares whole output file to COBOL output.
 * 
 * Configuration:
 * - Set system property coroner.java.classpath to the directory containing {java_class}.class
 *   Example: -Dcoroner.java.classpath=/path/to/classes
 *   Fallback: environment variable CORONER_JAVA_CLASSPATH
 * - Set system property coroner.java.bin to the java executable path (default: "java")
 *   Example: -Dcoroner.java.bin=/path/to/java
 */"""
        
        # Java test source for multi-row
        java_source = f'''{card_header}{header}
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import static org.junit.jupiter.api.Assertions.*;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.concurrent.TimeUnit;

public class ZombieRegressionTest {{
    
    @Test
    public void testMinimalFailingCase(@TempDir Path tempDir) throws Exception {{
        // Write minimal case input rows
        Path inputFile = tempDir.resolve("input.csv");
        Files.writeString(inputFile, "{input_csv_escaped}");
        
        // Get classpath configuration
        String classpath = System.getProperty("coroner.java.classpath");
        if (classpath == null) {{
            classpath = System.getenv("CORONER_JAVA_CLASSPATH");
        }}
        if (classpath == null) {{
            fail("coroner.java.classpath system property or CORONER_JAVA_CLASSPATH environment variable must be set");
        }}
        
        // Get java executable configuration
        String javaExec = System.getProperty("coroner.java.bin", "java");
        
        // Run Java program as subprocess
        Path outputFile = tempDir.resolve("output.csv");
        ProcessBuilder pb = new ProcessBuilder(
            javaExec, "-cp", classpath, "{java_class}"
        );
        pb.environment().put("INPUT_FILE", inputFile.toString());
        pb.environment().put("OUTPUT_FILE", outputFile.toString());
        
        Process process = pb.start();
        boolean completed = process.waitFor(10, TimeUnit.SECONDS);
        
        if (!completed) {{
            process.destroyForcibly();
            fail("Java program timed out after 10 seconds");
        }}
        
        int exitCode = process.exitValue();
        if (exitCode != 0) {{
            fail("Java program exited with code " + exitCode);
        }}
        
        // Check that output file was created
        if (!Files.exists(outputFile)) {{
            fail("Output file was not created: " + outputFile);
        }}
        
        // Read actual output
        String actualOutput = Files.readString(outputFile);
        
        // Expected COBOL output
        String expectedOutput = "{expected_output_escaped}";
        
        // Assert whole output equals COBOL output
        assertEquals(expectedOutput, actualOutput, 
            "Output file should match COBOL output exactly");
    }}
}}
'''
    else:
        # Single-case: original logic
        _generate_single_case_test(
            card_header, minimal_case, input_row, expected_output, java_class, 
            schema, divergent_field, cobol_value, java_value, output_path
        )
        return
    
    # Write to file
    Path(output_path).write_text(java_source)


def _generate_single_case_test(
    card_header: str,
    minimal_case: CaseResult,
    input_row: dict[str, str],
    expected_output: dict[str, str],
    java_class: str,
    schema: Schema,
    divergent_field: str,
    cobol_value: str,
    java_value: str,
    output_path: str
) -> None:
    """Generate JUnit test for single-case schema."""
    # Build header comment with test metadata
    header = f"""/**
 * Generated by Coroner from minimal failing case.
 * 
 * Case ID: {minimal_case.case_id}
 * Divergent field: {divergent_field}
 * COBOL value: {cobol_value}
 * Java value: {java_value}
 * 
 * This test reproduces the divergence on the Java side.
 * 
 * Configuration:
 * - Set system property coroner.java.classpath to the directory containing {java_class}.class
 *   Example: -Dcoroner.java.classpath=/path/to/classes
 *   Fallback: environment variable CORONER_JAVA_CLASSPATH
 * - Set system property coroner.java.bin to the java executable path (default: "java")
 *   Example: -Dcoroner.java.bin=/path/to/java
 */"""
    
    # Build input CSV content (header + row)
    input_columns = [col.name for col in schema.input_columns]
    input_header = ",".join(input_columns)
    input_values = [str(input_row.get(col, "")) for col in input_columns]
    input_csv_line = ",".join(input_values)
    input_csv_content = f"{input_header}\\n{input_csv_line}\\n"
    
    # Build output column names for parsing
    output_columns = [col.name for col in schema.output_columns]
    
    # Java test source
    java_source = f'''{card_header}{header}
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import static org.junit.jupiter.api.Assertions.*;

import java.io.BufferedReader;
import java.io.FileReader;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.HashMap;
import java.util.Map;
import java.util.concurrent.TimeUnit;

public class ZombieRegressionTest {{
    
    @Test
    public void testMinimalFailingCase(@TempDir Path tempDir) throws Exception {{
        // Write minimal case input
        Path inputFile = tempDir.resolve("input.csv");
        Files.writeString(inputFile, "{input_csv_content}");
        
        // Get classpath configuration
        String classpath = System.getProperty("coroner.java.classpath");
        if (classpath == null) {{
            classpath = System.getenv("CORONER_JAVA_CLASSPATH");
        }}
        if (classpath == null) {{
            fail("coroner.java.classpath system property or CORONER_JAVA_CLASSPATH environment variable must be set");
        }}
        
        // Get java executable configuration
        String javaExec = System.getProperty("coroner.java.bin", "java");
        
        // Run Java program as subprocess
        Path outputFile = tempDir.resolve("output.csv");
        ProcessBuilder pb = new ProcessBuilder(
            javaExec, "-cp", classpath, "{java_class}"
        );
        pb.environment().put("INPUT_FILE", inputFile.toString());
        pb.environment().put("OUTPUT_FILE", outputFile.toString());
        
        Process process = pb.start();
        boolean completed = process.waitFor(10, TimeUnit.SECONDS);
        
        if (!completed) {{
            process.destroyForcibly();
            fail("Java program timed out after 10 seconds");
        }}
        
        int exitCode = process.exitValue();
        if (exitCode != 0) {{
            fail("Java program exited with code " + exitCode);
        }}
        
        // Check that output file was created
        if (!Files.exists(outputFile)) {{
            fail("Output file was not created: " + outputFile);
        }}
        
        // Parse output CSV
        Map<String, String> outputRow = parseOutputCsv(outputFile);
        
        // Assert divergent field equals COBOL value
        String actualValue = outputRow.get("{divergent_field}");
        if (actualValue == null) {{
            // Show output file content for debugging
            String outputContent = Files.readString(outputFile);
            fail("Field {divergent_field} not found in output. Output content:\\n" + outputContent + "\\nParsed keys: " + outputRow.keySet());
        }}
        assertEquals("{cobol_value}", actualValue, 
            "Field {divergent_field} should match COBOL value");
    }}
    
    private Map<String, String> parseOutputCsv(Path csvPath) throws IOException {{
        Map<String, String> result = new HashMap<>();
        
        try (BufferedReader reader = new BufferedReader(new FileReader(csvPath.toFile()))) {{
            // Read header
            String headerLine = reader.readLine();
            if (headerLine == null) {{
                return result;
            }}
            String[] headers = headerLine.split(",", -1);
            
            // Read first data row
            String dataLine = reader.readLine();
            if (dataLine == null) {{
                return result;
            }}
            String[] values = dataLine.split(",", -1);
            
            // Build map
            for (int i = 0; i < headers.length && i < values.length; i++) {{
                result.put(headers[i], values[i]);
            }}
        }}
        
        return result;
    }}
}}
'''
    
    # Write to file
    Path(output_path).write_text(java_source)


def verify_junit_test(test_path: str, java_path: str, junit_jar: str, work_dir: str) -> tuple[str, str]:
    """
    Verify that a generated JUnit test compiles and runs correctly.
    
    Compiles the Java port and the JUnit test, then runs the test with JUnit.
    
    Args:
        test_path: Path to ZombieRegressionTest.java
        java_path: Path to the Java port source file
        junit_jar: Path to junit-platform-console-standalone jar
        work_dir: Working directory for compilation and test execution (may be relative)
    
    Returns:
        (result, summary):
            - result: "passed" if tests found >= 1 and failed = 0
                     "failed" if tests found >= 1 and every failure is AssertionFailedError
                     "error" otherwise (0 tests found, setup error, compilation failure)
            - summary: JUnit summary text or error message
    """
    # Resolve work_dir to absolute path
    work_path = Path(work_dir).resolve()
    work_path.mkdir(parents=True, exist_ok=True)
    
    test_file = Path(test_path).resolve()
    java_file = Path(java_path).resolve()
    junit_jar_path = Path(junit_jar).resolve()
    
    if not test_file.exists():
        return ("error", f"Test file not found: {test_path}")
    
    if not java_file.exists():
        return ("error", f"Java file not found: {java_path}")
    
    if not junit_jar_path.exists():
        return ("error", f"JUnit jar not found: {junit_jar}")
    
    # Extract test class name from test file
    test_class = test_file.stem
    
    # Compile Java port
    try:
        from coroner.run import JAVAC_ENCODING
        result = subprocess.run(
            ["javac"] + JAVAC_ENCODING + ["-d", str(work_path), str(java_file)],
            capture_output=True,
            text=True,
            timeout=30
        )
        if result.returncode != 0:
            return ("error", f"Java compilation failed:\n{result.stderr}")
    except Exception as e:
        return ("error", f"Java compilation error: {e}")
    
    # Compile test
    try:
        result = subprocess.run(
            ["javac"] + JAVAC_ENCODING + ["-cp", f"{junit_jar_path}:{work_path}", "-d", str(work_path), str(test_file)],
            capture_output=True,
            text=True,
            timeout=30
        )
        if result.returncode != 0:
            return ("error", f"Test compilation failed:\n{result.stderr}")
    except Exception as e:
        return ("error", f"Test compilation error: {e}")
    
    # Run test with JUnit, using absolute classpath and explicit class selection
    try:
        from coroner.run import JAVA_LOCALE_PROPERTIES
        result = subprocess.run(
            [
                "java"
            ] + JAVA_LOCALE_PROPERTIES + [
                f"-Dcoroner.java.classpath={work_path}",
                "-jar", str(junit_jar_path),
                "execute",
                "--classpath", str(work_path),
                "--select-class", test_class,
                "--disable-ansi-colors",
                "--disable-banner"
            ],
            capture_output=True,
            text=True,
            timeout=30
        )
        
        summary = result.stdout + result.stderr
        
        # Parse JUnit summary counts
        # Expected format: "[         N tests successful      ]"
        #                  "[         M tests failed          ]"
        tests_found = 0
        tests_failed = 0
        
        for line in summary.split('\n'):
            if 'tests successful' in line:
                parts = line.split()
                for i, part in enumerate(parts):
                    if part == 'tests' and i > 0:
                        try:
                            tests_found += int(parts[i - 1])
                        except ValueError:
                            pass
            elif 'tests failed' in line:
                parts = line.split()
                for i, part in enumerate(parts):
                    if part == 'tests' and i > 0:
                        try:
                            tests_failed = int(parts[i - 1])
                            tests_found += tests_failed
                        except ValueError:
                            pass
        
        # No tests found
        if tests_found == 0:
            return ("error", f"0 tests found. Summary:\n{summary}")
        
        # Tests found and all passed
        if tests_failed == 0:
            return ("passed", summary)
        
        # Tests found and some failed: check if all failures are AssertionFailedError
        has_assertion_error = 'org.opentest4j.AssertionFailedError' in summary
        has_other_error = ('Exception' in summary and 'AssertionFailedError' not in summary) or 'Error' in summary.replace('AssertionFailedError', '')
        
        # If all failures are assertion failures (real output mismatches)
        if has_assertion_error and not has_other_error:
            return ("failed", summary)
        
        # Otherwise it's a setup or execution error
        return ("error", summary)
        
    except Exception as e:
        return ("error", f"Test execution error: {e}")
