"""JUnit test generation module for Coroner."""

from pathlib import Path
from coroner.compare import CaseResult
from coroner.parse.schema import Schema


def generate_junit_test(
    minimal_case: CaseResult,
    input_row: dict[str, str],
    expected_output: dict[str, str],
    java_class: str,
    schema: Schema,
    output_path: str,
    card: str | None = None
) -> None:
    """
    Generate a JUnit 5 source test that reproduces the divergence.
    
    The test writes the minimal case input to a temp file, runs the Java program
    as a subprocess, and asserts the divergent field equals the COBOL value.
    
    Args:
        minimal_case: The minimal failing case
        input_row: Input values for the minimal case
        expected_output: Expected COBOL output values
        java_class: Java main class name (e.g., "CreditFees")
        schema: Schema with column definitions
        output_path: Where to write ZombieRegressionTest.java
        card: Optional Given/When/Then card to prepend as header comment
    """
    # Extract divergent field info
    if not minimal_case.divergent_fields:
        raise ValueError("Minimal case has no divergent fields")
    
    first_divergent = minimal_case.divergent_fields[0]
    
    # Handle structured divergent_fields
    if isinstance(first_divergent, dict):
        divergent_field = first_divergent.get("field_name", "<row>")
        cobol_value = first_divergent.get("cobol_value", str(first_divergent.get("cobol_values", {})))
        java_value = first_divergent.get("java_value", str(first_divergent.get("java_values", {})))
    else:
        # Legacy tuple format (shouldn't happen with new code)
        divergent_field, cobol_value, java_value = first_divergent
    
    # Build card header if provided
    card_header = ""
    if card:
        # Format card as a block comment
        card_lines = card.split('\n')
        card_header = "/**\n * Given/When/Then card:\n *\n"
        for line in card_lines:
            card_header += f" * {line}\n"
        card_header += " */\n\n"
    
    # Build header comment with test metadata
    header = f"""/**
 * Generated by Coroner from minimal failing case.
 * 
 * Case ID: {minimal_case.case_id}
 * Divergent field: {divergent_field}
 * COBOL value: {cobol_value}
 * Java value: {java_value}
 * 
 * This test reproduces the divergence on the Java side.
 * 
 * Configuration:
 * - Set system property coroner.java.classpath to the directory containing {java_class}.class
 *   Example: -Dcoroner.java.classpath=/path/to/classes
 *   Fallback: environment variable CORONER_JAVA_CLASSPATH
 * - Set system property coroner.java.bin to the java executable path (default: "java")
 *   Example: -Dcoroner.java.bin=/path/to/java
 */"""
    
    # Build input CSV content (header + row)
    input_columns = [col.name for col in schema.input_columns]
    input_header = ",".join(input_columns)
    input_values = [str(input_row.get(col, "")) for col in input_columns]
    input_csv_line = ",".join(input_values)
    input_csv_content = f"{input_header}\\n{input_csv_line}\\n"
    
    # Build output column names for parsing
    output_columns = [col.name for col in schema.output_columns]
    
    # Java test source
    java_source = f'''{card_header}{header}
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import static org.junit.jupiter.api.Assertions.*;

import java.io.BufferedReader;
import java.io.FileReader;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.HashMap;
import java.util.Map;
import java.util.concurrent.TimeUnit;

public class ZombieRegressionTest {{
    
    @Test
    public void testMinimalFailingCase(@TempDir Path tempDir) throws Exception {{
        // Write minimal case input
        Path inputFile = tempDir.resolve("input.csv");
        Files.writeString(inputFile, "{input_csv_content}");
        
        // Get classpath configuration
        String classpath = System.getProperty("coroner.java.classpath");
        if (classpath == null) {{
            classpath = System.getenv("CORONER_JAVA_CLASSPATH");
        }}
        if (classpath == null) {{
            fail("coroner.java.classpath system property or CORONER_JAVA_CLASSPATH environment variable must be set");
        }}
        
        // Get java executable configuration
        String javaExec = System.getProperty("coroner.java.bin", "java");
        
        // Run Java program as subprocess
        Path outputFile = tempDir.resolve("output.csv");
        ProcessBuilder pb = new ProcessBuilder(
            javaExec, "-cp", classpath, "{java_class}"
        );
        pb.environment().put("INPUT_FILE", inputFile.toString());
        pb.environment().put("OUTPUT_FILE", outputFile.toString());
        
        Process process = pb.start();
        boolean completed = process.waitFor(10, TimeUnit.SECONDS);
        
        if (!completed) {{
            process.destroyForcibly();
            fail("Java program timed out after 10 seconds");
        }}
        
        int exitCode = process.exitValue();
        if (exitCode != 0) {{
            fail("Java program exited with code " + exitCode);
        }}
        
        // Check that output file was created
        if (!Files.exists(outputFile)) {{
            fail("Output file was not created: " + outputFile);
        }}
        
        // Parse output CSV
        Map<String, String> outputRow = parseOutputCsv(outputFile);
        
        // Assert divergent field equals COBOL value
        String actualValue = outputRow.get("{divergent_field}");
        if (actualValue == null) {{
            // Show output file content for debugging
            String outputContent = Files.readString(outputFile);
            fail("Field {divergent_field} not found in output. Output content:\\n" + outputContent + "\\nParsed keys: " + outputRow.keySet());
        }}
        assertEquals("{cobol_value}", actualValue, 
            "Field {divergent_field} should match COBOL value");
    }}
    
    private Map<String, String> parseOutputCsv(Path csvPath) throws IOException {{
        Map<String, String> result = new HashMap<>();
        
        try (BufferedReader reader = new BufferedReader(new FileReader(csvPath.toFile()))) {{
            // Read header
            String headerLine = reader.readLine();
            if (headerLine == null) {{
                return result;
            }}
            String[] headers = headerLine.split(",", -1);
            
            // Read first data row
            String dataLine = reader.readLine();
            if (dataLine == null) {{
                return result;
            }}
            String[] values = dataLine.split(",", -1);
            
            // Build map
            for (int i = 0; i < headers.length && i < values.length; i++) {{
                result.put(headers[i], values[i]);
            }}
        }}
        
        return result;
    }}
}}
'''
    
    # Write to file
    Path(output_path).write_text(java_source)

